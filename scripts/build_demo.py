"""Export aggregate-only published results for the buildless demo."""

from __future__ import annotations

import argparse
from collections import defaultdict
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ATTACKS = [
    ("mtxA_seedmut", "PromptMe · seeds and mutations", "PromptMe"),
    ("mtxB_mutonly", "PromptMe · mutations only", "PromptMe"),
    ("gandalf_mtx", "Gandalf · RedAgent", "Gandalf"),
    ("pyrit_promptme", "PromptMe · PyRIT comparison", "PromptMe"),
    ("pyrit_gandalf", "Gandalf · PyRIT comparison", "Gandalf"),
]
JUDGES = [
    ("promptme", "PromptMe · historical replay", "exp2_summary.json"),
    ("gandalf", "Gandalf · judge replay", "gandalf_exp2/exp2_summary.json"),
]


def aggregate_cells(cells: list[dict]) -> list[dict]:
    groups: dict[tuple[str, str], list[int]] = defaultdict(lambda: [0, 0])
    seen: set[str] = set()
    for cell in cells:
        if cell["cell_key"] in seen:
            raise ValueError("Duplicate experiment cell")
        seen.add(cell["cell_key"])
        if not isinstance(cell["success"], bool):
            raise ValueError("Experiment success must be boolean")
        model, challenge = cell["attacker_model"], cell["challenge"]
        if not isinstance(model, str) or not isinstance(challenge, str):
            raise ValueError("Model and challenge must be strings")
        counts = groups[model, challenge]
        counts[0] += 1
        counts[1] += int(cell["success"])
    # Explicit allowlist: no prompts, responses, captured secrets or evidence.
    return [dict(model=model, challenge=challenge, runs=n, captures=k)
            for (model, challenge), (n, k) in sorted(groups.items())]


def judge_counts(rows: list[dict]) -> list[dict]:
    exported = []
    for row in rows:
        item = {"model": row["judge"]}
        for key in ("tp", "fp", "tn", "fn", "errors"):
            value = row.get(key, 0)
            if not isinstance(value, int) or isinstance(value, bool) or value < 0:
                raise ValueError("Judge counts must be nonnegative integers")
            item[key] = value
        exported.append(item)
    return exported


def build_data(root: Path = ROOT) -> dict:
    result_root = root / "experiments" / "results"
    attacks = []
    for dataset, label, target in ATTACKS:
        path = f"experiments/results/{dataset}/exp1_cells.jsonl"
        cells = [json.loads(line) for line in (root / path).read_text(encoding="utf-8").splitlines() if line.strip()]
        attacks.append(dict(id=dataset, label=label, target=target, source=path,
                            rows=aggregate_cells(cells)))
    judges = []
    for dataset, label, file in JUDGES:
        rows = json.loads((result_root / file).read_text(encoding="utf-8"))
        judges.append(dict(id=dataset, label=label, source=f"experiments/results/{file}",
                           rows=judge_counts(rows)))
    return {"schema": 1, "attacks": attacks, "judges": judges}


def render(data: dict) -> str:
    payload = json.dumps(data, ensure_ascii=True, sort_keys=True, indent=2).replace("<", "\\u003c")
    return "// Generated by scripts/build_demo.py; aggregate counts only.\nwindow.REDAGENT_DATA = " + payload + ";\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if committed data.js is stale")
    args = parser.parse_args()
    output = ROOT / "demo" / "data.js"
    expected = render(build_data())
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Demo data is stale; run python scripts/build_demo.py\n")
        print("Demo data matches the published source logs")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected, encoding="utf-8")
        print("Built demo/data.js from published aggregate counts")


if __name__ == "__main__":
    main()
